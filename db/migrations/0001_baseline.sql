-- [FIX] Tres cambios respecto a la base vieja:
--   1. Fuera usu_contrasena. Era text NOT NULL con las contraseñas en
--      claro. Las gestiona Supabase Auth (bcrypt).
--   2. auth_user_id: enlace con auth.users. Nullable porque los usuarios
