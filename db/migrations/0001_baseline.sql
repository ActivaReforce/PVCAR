-- [FIX] La base vieja tiene 9 constraints en esta tabla, de las cuales 3
-- están duplicadas literalmente:
--   check_different_times == evaluacion_tiempo_rangos_check1
--   check_max_op          == evaluacion_tiempo_rangos_evatieran_max_op_check
--   check_min_op          == evaluacion_tiempo_rangos_evatieran_min_op_check
-- Se conserva una de cada par. Quedan 6.
CREATE TABLE public.evaluacion_tiempo_rangos (
    evatieran_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    evaparam_id integer NOT NULL,
    evatieran_op_cero text NOT NULL,
    evatieran_tiempo_cero integer NOT NULL,
    evatieran_op_full text NOT NULL,
    evatieran_tiempo_full integer NOT NULL,
    CONSTRAINT check_different_times
        CHECK ((evatieran_tiempo_cero <> evatieran_tiempo_full)),
    CONSTRAINT check_min_op
        CHECK ((evatieran_op_cero = ANY (ARRAY['<'::text, '<='::text, '>'::text, '>='::text]))),
    CONSTRAINT check_max_op
        CHECK ((evatieran_op_full = ANY (ARRAY['<'::text, '<='::text, '>'::text, '>='::text]))),
    CONSTRAINT check_min_tiempo_positive
        CHECK ((evatieran_tiempo_cero > 0)),
    CONSTRAINT check_max_tiempo_positive
        CHECK ((evatieran_tiempo_full > 0)),
    CONSTRAINT evaluacion_tiempo_rangos_check
        CHECK ((((evatieran_op_cero = ANY (ARRAY['<'::text, '<='::text]))
                 AND (evatieran_op_full = ANY (ARRAY['>'::text, '>='::text]))
                 AND (evatieran_tiempo_full > evatieran_tiempo_cero))
             OR ((evatieran_op_cero = ANY (ARRAY['>'::text, '>='::text]))
                 AND (evatieran_op_full = ANY (ARRAY['<'::text, '<='::text]))
                 AND (evatieran_tiempo_full < evatieran_tiempo_cero))))
);

