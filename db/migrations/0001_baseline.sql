CREATE FUNCTION public.update_evaluacion_puntaje_total()
    RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'public'
    AS $$
DECLARE
    target_eva_id INTEGER;
BEGIN
    IF TG_OP = 'DELETE' THEN
        target_eva_id := OLD.eva_id;
    ELSE
        target_eva_id := NEW.eva_id;
    END IF;

    UPDATE evaluacion
    SET eva_puntaje_total = (
        SELECT COALESCE(SUM(evaparam_puntaje), 0)
        FROM evaluacion_parametro ep
        WHERE ep.eva_id = target_eva_id
    )
    WHERE eva_id = target_eva_id;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

