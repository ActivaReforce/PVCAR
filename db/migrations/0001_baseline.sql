CREATE FUNCTION public.delete_student_evaluation(p_evaninopen_id integer)
    RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
  -- Borra todos los intentos de esta evaluación
  DELETE FROM evaluacion_intento
  WHERE evaninopen_id = p_evaninopen_id;

  -- Devuelve la evaluación del estudiante a pendiente (est_id = 6)
  UPDATE evaluacion_nino_pendiente
  SET est_id = 6,
      usu_id_registrador = NULL,
      evaninopen_fecha_finalizacion = NULL
  WHERE evaninopen_id = p_evaninopen_id;
END;
$$;

CREATE FUNCTION public.handle_nino_asignacion_insert()
    RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'public'
    AS $$
DECLARE
    eval_record RECORD;
BEGIN
    -- Al inscribir un estudiante en un horario, se le crean las
    -- evaluaciones pendientes de las evaluaciones activas de ese horario.
    FOR eval_record IN
        SELECT eva_id
        FROM evaluacion_asignacion
        WHERE colacthor_id = NEW.colacthor_id
          AND est_id = 1
    LOOP
        IF EXISTS (
            SELECT 1
            FROM evaluacion_nino_pendiente
            WHERE ninoasig_id = NEW.ninoasig_id
              AND eva_id = eval_record.eva_id
        ) THEN
            -- Existe: si estaba inactiva, se reactiva como pendiente
            UPDATE evaluacion_nino_pendiente
            SET est_id = 6
            WHERE ninoasig_id = NEW.ninoasig_id
              AND eva_id = eval_record.eva_id
              AND est_id = 2;
        ELSE
            INSERT INTO evaluacion_nino_pendiente (
                eva_id, ninoasig_id, est_id, usu_id_registrador
            ) VALUES (
                eval_record.eva_id, NEW.ninoasig_id, 6, NULL
            );
        END IF;
    END LOOP;

    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION public.handle_nino_asignacion_insert() IS
    'Se le quitó un SELECT a existing_ninoasig_id cuyo resultado no se usaba: '
    'la versión vieja lo calculaba y lo descartaba.';

CREATE FUNCTION public.handle_nino_asignacion_update()
    RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'public'
    AS $$
BEGIN
    -- Si la asignación se da de baja (est_id 1 -> 2), se inactivan sus
    -- evaluaciones pendientes.
    IF OLD.est_id = 1 AND NEW.est_id = 2 THEN
        UPDATE evaluacion_nino_pendiente
        SET est_id = 2
        WHERE ninoasig_id = NEW.ninoasig_id
          AND est_id IN (1, 6, 7);
    END IF;

    RETURN NEW;
END;
$$;

CREATE FUNCTION public.reactivate_nino_asignacion(
        p_nino_id integer,
        p_colacthor_id integer)
    RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO 'public'
    AS $$
DECLARE
    existing_ninoasig_id INTEGER;
    eval_record RECORD;
BEGIN
    SELECT ninoasig_id INTO existing_ninoasig_id
    FROM nino_asignacion
    WHERE nino_id = p_nino_id
      AND colacthor_id = p_colacthor_id
      AND est_id <> 1;

    IF existing_ninoasig_id IS NULL THEN
        RETURN NULL;
    END IF;

    UPDATE nino_asignacion
    SET est_id = 1,
        ninoasig_fecha_inscripcion = now(),
        ninoasig_fecha_baja = NULL
    WHERE ninoasig_id = existing_ninoasig_id;

    FOR eval_record IN
        SELECT eva_id
        FROM evaluacion_asignacion
        WHERE colacthor_id = p_colacthor_id
          AND est_id = 1
    LOOP
        IF EXISTS (
            SELECT 1
            FROM evaluacion_nino_pendiente
            WHERE ninoasig_id = existing_ninoasig_id
              AND eva_id = eval_record.eva_id
        ) THEN
            UPDATE evaluacion_nino_pendiente
            SET est_id = 6
            WHERE ninoasig_id = existing_ninoasig_id
              AND eva_id = eval_record.eva_id
              AND est_id = 2;
        ELSE
            INSERT INTO evaluacion_nino_pendiente (
                eva_id, ninoasig_id, est_id, usu_id_registrador
            ) VALUES (
                eval_record.eva_id, existing_ninoasig_id, 6, NULL
            );
        END IF;
    END LOOP;

    RETURN existing_ninoasig_id;
END;
$$;

CREATE FUNCTION public.set_role_permissions(
        p_actor_usu_id integer,
        p_target_rol_id integer,
        p_enable_modules text[] DEFAULT ARRAY[]::text[],
        p_disable_modules text[] DEFAULT ARRAY[]::text[],
        p_action text DEFAULT 'ver'::text)
    RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
  -- Solo Admin PVCAR (rol_id = 1) puede administrar permisos
  IF NOT EXISTS (
    SELECT 1
    FROM public.usuario_rol ur
    WHERE ur.usu_id = p_actor_usu_id
      AND ur.rol_id = 1
  ) THEN
    RAISE EXCEPTION 'Not authorized to manage role permissions';
  END IF;

  IF p_enable_modules IS NULL THEN
    p_enable_modules := ARRAY[]::text[];
  END IF;
  IF p_disable_modules IS NULL THEN
    p_disable_modules := ARRAY[]::text[];
  END IF;

  INSERT INTO public.rol_permiso (rol_id, modulo, accion)
  SELECT p_target_rol_id, m, p_action
  FROM unnest(p_enable_modules) AS m
  ON CONFLICT (rol_id, modulo, accion) DO NOTHING;

  DELETE FROM public.rol_permiso
  WHERE rol_id = p_target_rol_id
    AND accion = p_action
    AND modulo = ANY (p_disable_modules);
END;
$$;

