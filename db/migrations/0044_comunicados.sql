-- PVCAR — 0044_comunicados.sql
-- Comunicados (pedido del cliente, 2026-11-11). Diseño en docs/comunicados.md.
--
-- Correos masivos por Resend Broadcasts sin entrar a Resend. Resend es solo
-- la tubería: los contactos, los segmentos y las plantillas viven aquí. Al
-- enviar, la plataforma sube los destinatarios a Resend dentro de un
-- segmento temporal, manda el broadcast y, cuando Resend dice "sent", borra
-- el segmento y los contactos que ella misma creó. Los contactos que ya
-- estaban en Resend antes no se tocan nunca.
--
-- Qué hace
--
-- 1. comunicado_contacto: gente interesada (nombre y correo). El correo es
--    único, en minúsculas.
-- 2. comunicado_segmento y comunicado_segmento_contacto: grupos de contactos.
--    Sin límite: el límite de 3 segmentos es de Resend y aquí no aplica.
-- 3. comunicado_plantilla: el marco HTML (logo, colores, pie) con el
--    marcador {{contenido}}.
-- 4. comunicado: borradores e historial. Del envío se guarda el texto del
--    destino ("Colegio X · 2.º EGB"), el total y el correo final; nunca la
--    lista de personas.
-- 5. comunicado_destinatario: lista de trabajo MIENTRAS se envía (para
--    retomar si el servidor se reinicia y saber qué contactos borrar en
--    Resend). Se vacía al terminar cada envío.
-- 6. Fila 'comunicados' en correo_config (remitente único).
--
-- Solo añade: el código desplegado sigue funcionando con ella aplicada.
-- Requiere 0001-0043. Idempotente. Todo en una transacción.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. Contactos
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.comunicado_contacto (
    comcon_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comcon_nombre         text        NOT NULL DEFAULT '',
    comcon_correo         text        NOT NULL,
    comcon_fecha_creacion timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_comcon_correo UNIQUE (comcon_correo),
    CONSTRAINT ck_comcon_correo CHECK (
        comcon_correo = lower(btrim(comcon_correo)) AND comcon_correo LIKE '%_@_%.__%'),
    CONSTRAINT ck_comcon_nombre CHECK (char_length(comcon_nombre) <= 120)
);

COMMENT ON TABLE public.comunicado_contacto IS
    'Contactos de Comunicados: gente interesada que no es representante. Solo el Propietario.';

-- ---------------------------------------------------------------------
-- 2. Segmentos
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.comunicado_segmento (
    comseg_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comseg_nombre         text        NOT NULL,
    comseg_fecha_creacion timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_comseg_nombre CHECK (char_length(btrim(comseg_nombre)) BETWEEN 1 AND 80)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_comseg_nombre
    ON public.comunicado_segmento (lower(comseg_nombre));

CREATE TABLE IF NOT EXISTS public.comunicado_segmento_contacto (
    comseg_id integer NOT NULL REFERENCES public.comunicado_segmento (comseg_id) ON DELETE CASCADE,
    comcon_id integer NOT NULL REFERENCES public.comunicado_contacto (comcon_id) ON DELETE CASCADE,
    PRIMARY KEY (comseg_id, comcon_id)
);

CREATE INDEX IF NOT EXISTS ix_comsegcon_contacto
    ON public.comunicado_segmento_contacto (comcon_id);

COMMENT ON TABLE public.comunicado_segmento IS
    'Grupos de contactos de Comunicados. Viven aquí; en Resend solo existe uno temporal por envío.';

-- ---------------------------------------------------------------------
-- 3. Plantillas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.comunicado_plantilla (
    complan_id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complan_nombre             text        NOT NULL,
    complan_html               text        NOT NULL,
    complan_fecha_creacion     timestamptz NOT NULL DEFAULT now(),
    complan_fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_complan_nombre CHECK (char_length(btrim(complan_nombre)) BETWEEN 1 AND 80),
    CONSTRAINT ck_complan_html CHECK (
        position('{{contenido}}' IN complan_html) > 0 AND char_length(complan_html) <= 300000)
);

COMMENT ON COLUMN public.comunicado_plantilla.complan_html IS
    'Marco del correo. {{contenido}} marca dónde va el texto de cada comunicado.';

-- ---------------------------------------------------------------------
-- 4. Comunicados (borradores e historial)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.comunicado (
    com_id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    com_asunto             text        NOT NULL DEFAULT '',
    com_cuerpo             text        NOT NULL DEFAULT '',
    com_modo               text        NOT NULL DEFAULT 'visual',
    complan_id             integer     REFERENCES public.comunicado_plantilla (complan_id) ON DELETE SET NULL,
    com_destinos           jsonb       NOT NULL DEFAULT '[]'::jsonb,
    com_estado             text        NOT NULL DEFAULT 'borrador',
    com_destino_texto      text,
    com_total              integer,
    com_html               text,
    com_error              text,
    com_resend_segmento    text,
    com_resend_broadcast   text,
    usu_id                 integer     REFERENCES public.usuario (usu_id) ON DELETE SET NULL,
    com_fecha_creacion     timestamptz NOT NULL DEFAULT now(),
    com_fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    com_fecha_envio        timestamptz,
    com_fecha_fin          timestamptz,
    CONSTRAINT ck_com_modo CHECK (com_modo IN ('visual', 'html')),
    CONSTRAINT ck_com_estado CHECK (com_estado IN (
        'borrador', 'en_cola', 'preparando', 'enviando', 'limpiando', 'enviado', 'fallido')),
    CONSTRAINT ck_com_asunto CHECK (char_length(com_asunto) <= 200),
    CONSTRAINT ck_com_cuerpo CHECK (char_length(com_cuerpo) <= 400000)
);

CREATE INDEX IF NOT EXISTS ix_com_estado ON public.comunicado (com_estado, com_fecha_envio);

COMMENT ON COLUMN public.comunicado.com_destinos IS
    'Lo elegido en "Para": [{tipo: contactos|segmento|representantes, ...}].';
COMMENT ON COLUMN public.comunicado.com_destino_texto IS
    'Al enviar: el destino en palabras ("Representantes · Colegio X · 2.º EGB"). No se guarda la lista de personas.';
COMMENT ON COLUMN public.comunicado.com_html IS
    'Al enviar: el correo tal cual salió (plantilla + contenido).';

-- ---------------------------------------------------------------------
-- 5. Lista de trabajo del envío (se vacía al terminar)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.comunicado_destinatario (
    com_id        integer NOT NULL REFERENCES public.comunicado (com_id) ON DELETE CASCADE,
    comdes_correo text    NOT NULL,
    comdes_nombre text    NOT NULL DEFAULT '',
    comdes_estado text    NOT NULL DEFAULT 'pendiente',
    PRIMARY KEY (com_id, comdes_correo),
    CONSTRAINT ck_comdes_estado CHECK (comdes_estado IN (
        'pendiente', 'creando', 'creado', 'existia', 'borrado'))
);

COMMENT ON TABLE public.comunicado_destinatario IS
    'Solo mientras un comunicado se envía. existia = ya estaba en Resend y no se borra; creado = lo subió la plataforma y se borra al terminar.';

-- ---------------------------------------------------------------------
-- 6. Remitente
-- ---------------------------------------------------------------------
ALTER TABLE public.correo_config DROP CONSTRAINT IF EXISTS ck_corcfg_tipo;
ALTER TABLE public.correo_config ADD CONSTRAINT ck_corcfg_tipo
    CHECK (corcfg_tipo IN ('inscripciones', 'inscripciones_aviso', 'novedades', 'ausencias',
                           'mensualidades', 'comunicados'));

INSERT INTO public.correo_config (corcfg_tipo, corcfg_nombre, corcfg_usuario)
VALUES ('comunicados', 'Activa Reforce', 'comunicados')
ON CONFLICT (corcfg_tipo) DO NOTHING;

-- ---------------------------------------------------------------------
-- Seguridad: solo el backend (service_role)
-- ---------------------------------------------------------------------
ALTER TABLE public.comunicado_contacto          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comunicado_contacto          FORCE  ROW LEVEL SECURITY;
ALTER TABLE public.comunicado_segmento          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comunicado_segmento          FORCE  ROW LEVEL SECURITY;
ALTER TABLE public.comunicado_segmento_contacto ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comunicado_segmento_contacto FORCE  ROW LEVEL SECURITY;
ALTER TABLE public.comunicado_plantilla         ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comunicado_plantilla         FORCE  ROW LEVEL SECURITY;
ALTER TABLE public.comunicado                   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comunicado                   FORCE  ROW LEVEL SECURITY;
ALTER TABLE public.comunicado_destinatario      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comunicado_destinatario      FORCE  ROW LEVEL SECURITY;

REVOKE ALL ON public.comunicado_contacto, public.comunicado_segmento,
              public.comunicado_segmento_contacto, public.comunicado_plantilla,
              public.comunicado, public.comunicado_destinatario
    FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON public.comunicado_contacto, public.comunicado_segmento,
       public.comunicado_segmento_contacto, public.comunicado_plantilla,
       public.comunicado, public.comunicado_destinatario
    TO service_role;

-- ---------------------------------------------------------------------
-- Verificación
-- ---------------------------------------------------------------------
DO $$
DECLARE
    tablas    int;
    sin_rls   int;
    expuestas int;
BEGIN
    SELECT count(*) INTO tablas
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
      AND c.relname IN ('comunicado_contacto', 'comunicado_segmento', 'comunicado_segmento_contacto',
                        'comunicado_plantilla', 'comunicado', 'comunicado_destinatario');
    IF tablas <> 6 THEN
        RAISE EXCEPTION 'Faltan tablas de comunicados (hay % de 6)', tablas;
    END IF;

    SELECT count(*) INTO sin_rls
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
      AND c.relname LIKE 'comunicado%'
      AND (NOT c.relrowsecurity OR NOT c.relforcerowsecurity);
    IF sin_rls > 0 THEN
        RAISE EXCEPTION 'Hay % tabla(s) de comunicados sin RLS', sin_rls;
    END IF;

    SELECT count(*) INTO expuestas
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
      AND c.relname LIKE 'comunicado%'
      AND (has_table_privilege('anon', c.oid, 'SELECT')
        OR has_table_privilege('authenticated', c.oid, 'SELECT'));
    IF expuestas > 0 THEN
        RAISE EXCEPTION 'Hay % tabla(s) de comunicados legibles por anon o authenticated', expuestas;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM public.correo_config WHERE corcfg_tipo = 'comunicados') THEN
        RAISE EXCEPTION 'No quedó la fila de comunicados en correo_config';
    END IF;
END $$;

COMMIT;
